package com.student.model;

public class ToBoMon {
	private int maTo;
	private String tenTo;
	private String moTa;
	private int maToTruong;
	private String tenToTruong;
	private int soLuongGiaoVien;

	public ToBoMon() {
	}

	// Getters & Setters
	public int getMaTo() {
		return maTo;
	}

	public void setMaTo(int maTo) {
		this.maTo = maTo;
	}

	public String getTenTo() {
		return tenTo;
	}

	public void setTenTo(String tenTo) {
		this.tenTo = tenTo;
	}

	public String getMoTa() {
		return moTa;
	}

	public void setMoTa(String moTa) {
		this.moTa = moTa;
	}

	public int getMaToTruong() {
		return maToTruong;
	}

	public void setMaToTruong(int maToTruong) {
		this.maToTruong = maToTruong;
	}

	public String getTenToTruong() {
		return tenToTruong;
	}

	public void setTenToTruong(String tenToTruong) {
		this.tenToTruong = tenToTruong;
	}

	public int getSoLuongGiaoVien() {
		return soLuongGiaoVien;
	}

	public void setSoLuongGiaoVien(int soLuongGiaoVien) {
		this.soLuongGiaoVien = soLuongGiaoVien;
	}
}